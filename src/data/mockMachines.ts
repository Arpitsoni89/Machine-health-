function generateMockHistory(temp: number, vib: number, pwr: number, risk: number, hasAnomaly: boolean) {
  const points = [];
  const now = Date.now();
  for (let i = 24; i >= 0; i--) {
    const time = new Date(now - i * 3600 * 1000);
    const hourLabel = time.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' });
    const isRecent = i <= 3;
    const factor = isRecent && hasAnomaly ? 1.0 : (0.7 + Math.random() * 0.15);

    points.push({
      timestamp: hourLabel,
      temperature: Number((temp * factor).toFixed(1)),
      vibration: Number((vib * factor).toFixed(2)),
      power: Number((pwr * factor).toFixed(1)),
      riskScore: Math.round(risk * factor),
      isAnomaly: isRecent && hasAnomaly,
    });
  }
  return points;
}
